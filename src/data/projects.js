export function getProject(slug) {
  return projects.find((p) => p.slug === slug)
}

/**
 * Responsive WebP sources generated by scripts/optimise-images.py.
 * '/portfolio/x-desktop.jpg' → 640w/1280w WebP; '/portfolio/x-mobile.jpg' → 320w/640w.
 */
export function portfolioSrcSet(src) {
  const m = /^\/portfolio\/(.+-(desktop|mobile))\.jpg$/.exec(src || '')
  if (!m) return undefined
  const [a, b] = m[2] === 'desktop' ? [640, 1280] : [320, 640]
  return `/portfolio/${m[1]}-${a}.webp ${a}w, /portfolio/${m[1]}-${b}.webp ${b}w`
}
